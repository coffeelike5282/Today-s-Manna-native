export const getRandomPrayerResolution = (dateString: string) => {
    // Use date as seed for daily consistency
    const seed = dateString.split('-').reduce((acc, part) => acc + parseInt(part), 0);
    const index = seed % PRAYER_RESOLUTIONS.length;
    return PRAYER_RESOLUTIONS[index];
};
